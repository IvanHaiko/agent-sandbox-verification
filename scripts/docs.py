"""Build/check the current-guide index and map source paths to documentation.

Frontmatter is a JSON object between --- lines (also valid YAML). No dependency
or scanning of historical evidence is needed. Run from any working directory.
"""
import argparse
import fnmatch
import hashlib
import json
from pathlib import Path, PurePosixPath, PureWindowsPath
import re
import sys

ROOT = Path(__file__).resolve().parent.parent


def relative(value):
    value = value.replace('\\', '/')
    path = PurePosixPath(value)
    if (not value or path.is_absolute() or PureWindowsPath(value).drive
            or '..' in path.parts or value == '.'):
        raise ValueError(f'Expected repository-relative path: {value!r}')
    return path.as_posix()


def load(root):
    records = []
    for folder in ('guides', 'templates'):
        for path in sorted((root / 'docs' / folder).rglob('*.md')):
            text = path.read_text(encoding='utf-8')
            if not text.startswith('---\n') or '\n---\n' not in text[4:]:
                raise ValueError(f'{path}: missing JSON frontmatter')
            metadata_text = text[4:].partition('\n---\n')[0]
            try:
                meta = json.loads(metadata_text)
            except json.JSONDecodeError as error:
                raise ValueError(f'{path}: invalid JSON frontmatter') from error
            if not isinstance(meta, dict):
                raise ValueError(f'{path}: frontmatter must be an object')
            for key in ('title', 'summary'):
                if not isinstance(meta.get(key), str) or not meta[key].strip():
                    raise ValueError(f'{path}: missing {key}')
                if any(c in meta[key] for c in '\r\n|[]'):
                    raise ValueError(f'{path}: unsupported table characters in {key}')
            if meta.get('status') != 'current':
                raise ValueError(f'{path}: expected status current')
            patterns = meta.get('related_files')
            if not isinstance(patterns, list) or not patterns:
                raise ValueError(f'{path}: related_files must be a nonempty list')
            for pattern in patterns:
                if not isinstance(pattern, str):
                    raise ValueError(f'{path}: related_files entries must be strings')
                pattern = relative(pattern)
                if pattern != 'docs/README.md' and not any(p.is_file() for p in root.glob(pattern)):
                    raise ValueError(f'{path}: unmatched related_files pattern {pattern}')
            if len(text.splitlines()) > 180:
                raise ValueError(f'{path}: current guide exceeds 180 lines; split by topic')
            records.append((path.relative_to(root).as_posix(), meta))
    if not records:
        raise ValueError('No current guides or templates found')
    return records


def render(records):
    lines = ['# Documentation index', '',
             'Generated by `python scripts/docs.py build`. Edit guide frontmatter, then rebuild.', '',
             'Start with the workflow guide. Read other guides only as needed.',
             'These are current instructions; stage reports record historical observations.', '',
             '| Guide | When to read |', '| --- | --- |']
    for name, meta in records:
        lines.append(f'| [{meta["title"]}]({name.removeprefix("docs/")}) | {meta["summary"]} |')
    lines += ['', '## Historical evidence', '',
              '- [Architecture decision](../STAGE29_ARCHITECTURE_DECISION.md)',
              '- [Native migration](../STAGE30_MIGRATION_REPORT.md)',
              '- [Medium-risk dogfooding](../STAGE31_DOGFOODING_REPORT.md)',
              '- [High-risk dogfooding](../STAGE32_HIGH_RISK_DOGFOODING_REPORT.md)',
              '- [Index integrity and compatibility](../STAGE33_INTEGRITY_AND_COMPATIBILITY_REPORT.md)',
              '- [Sandbox verification, Codex and Claude Code](../STAGE34_SANDBOX_VERIFICATION_REPORT.md)',
              '- [Earlier history](history/README.md)', '',
              'Verification directories contain retained contracts, receipts, fixtures and failures.',
              'They are excluded from guide indexing and must not be rewritten to satisfy documentation checks.', '']
    return '\n'.join(lines)


SKILL_SOURCE = PurePosixPath('.agents/skills')
SKILL_MIRROR = PurePosixPath('.claude/skills')


def skill_mirrors(root):
    """Expected Claude Code skill copies: {mirror path: source bytes}.

    `.agents/skills/` is canonical (Codex). Claude Code discovers project skills only
    under `.claude/skills/`, so build writes exact byte copies and check rejects drift.
    """
    source = root / SKILL_SOURCE
    if not source.is_dir():
        return {}
    return {(SKILL_MIRROR / path.relative_to(source).as_posix()).as_posix(): path.read_bytes()
            for path in sorted(source.rglob('*')) if path.is_file()}


def stale_mirrors(root):
    """Differences inside mirrored skill directories only.

    Other `.claude/skills/` entries (Claude-only skills) are never inspected or removed.
    """
    expected = skill_mirrors(root)
    source = root / SKILL_SOURCE
    names = sorted(p.name for p in source.iterdir() if p.is_dir()) if source.is_dir() else []
    actual = {}
    for name in names:
        folder = root / SKILL_MIRROR / name
        if folder.is_dir():
            actual.update({path.relative_to(root).as_posix(): path.read_bytes()
                           for path in sorted(folder.rglob('*')) if path.is_file()})
    return sorted(name for name in expected.keys() | actual.keys()
                  if expected.get(name) != actual.get(name))


def sync_mirrors(root):
    """Write expected copies; remove extra files inside mirrored skill directories."""
    expected = skill_mirrors(root)
    for name in stale_mirrors(root):
        path = root / name
        if name in expected:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected[name])
        else:
            path.unlink()


RESULTS = PurePosixPath('docs/stage34-verification/summary.json')
RESULTS_START = ('<!-- results:start (generated by scripts/docs.py build from '
                 + RESULTS.as_posix() + ') -->')
RESULTS_END = '<!-- results:end -->'
EXPECTED = {False: 'PASS', True: 'FAIL'}  # a negative control must fail


def render_results(root):
    """Results table for the root README, rendered from the recorded run summary."""
    rows = json.loads((root / RESULTS).read_text(encoding='utf-8'))
    final = [r for r in rows if r['run'].startswith('final-')]
    if not final:
        raise ValueError(f'{RESULTS}: no final-* runs recorded')
    lines = ['| Worker | Run | Expected | Verdict | Boundary violations found | Parent-watcher events |',
             '| --- | --- | --- | --- | --- | --- |']
    for r in sorted(final, key=lambda r: (r['vendor'], r['negative_control'])):
        kind = 'negative control (canaries exposed on purpose)' if r['negative_control'] else 'restricted worker'
        expected = EXPECTED[r['negative_control']]
        verdict = r['verdict'] + (' ✅' if r['verdict'] == expected else ' ❌')
        lines.append(f"| {r['version']} | {kind} | {expected} | {verdict} "
                     f"| {r['failures']} | {r['watcher_events']} |")
    other = len(rows) - len(final)
    lines += ['', f'{len(rows)} recorded runs in total. The {other} development runs, including '
              'failed and inconclusive ones, are kept in `docs/stage34-verification/runs/`.']
    return '\n'.join(lines)


def readme_with_results(root):
    """(current README text, regenerated text), or None when there is no results block."""
    readme = root / 'README.md'
    if not readme.exists():
        return None
    text = readme.read_text(encoding='utf-8')
    if RESULTS_START not in text:
        return None
    head, rest = text.split(RESULTS_START, 1)
    if RESULTS_END not in rest:
        raise ValueError('README.md: results block has no end marker')
    tail = rest.split(RESULTS_END, 1)[1]
    return text, f'{head}{RESULTS_START}\n{render_results(root)}\n{RESULTS_END}{tail}'


DIAGRAM_SOURCE = PurePosixPath('docs/architecture.mmd')
DIAGRAM = PurePosixPath('docs/architecture.svg')


def stale_diagram(root):
    """The rendered SVG must carry the hash of its current Mermaid source."""
    source = root / DIAGRAM_SOURCE
    if not source.exists():
        return None
    image = root / DIAGRAM
    text = source.read_bytes().decode('utf-8').replace('\r\n', '\n')
    digest = hashlib.sha256(text.encode('utf-8')).hexdigest()
    if not image.exists() or f'source-sha256: {digest}' not in image.read_text(encoding='utf-8')[:400]:
        return (f'{DIAGRAM} is stale or missing for {DIAGRAM_SOURCE}; '
                'run python scripts/render_diagram.py')
    return None


LINK = re.compile(r'\[[^\]]*\]\(([^)\s]+)\)')


def broken_links(root, records):
    """Relative Markdown links in the README, agent instructions and current guides."""
    pages = [root / n for n in ('README.md', 'CLAUDE.md', 'AGENTS.md')] + [root / n for n, _ in records]
    broken = []
    for page in pages:
        if not page.exists():
            continue
        text = re.sub(r'```.*?```', '', page.read_text(encoding='utf-8'), flags=re.S)
        for target in LINK.findall(text):
            if re.match(r'^[a-z][a-z0-9+.-]*:', target) or target.startswith('#'):
                continue
            path = target.split('#', 1)[0]
            if path and not (page.parent / path).exists():
                broken.append(f'{page.relative_to(root).as_posix()} -> {target}')
    return broken


def lookup(records, paths):
    paths = [relative(path) for path in paths]
    return {path: [name for name, meta in records
                   if any(fnmatch.fnmatchcase(path, pattern.replace('\\', '/'))
                          for pattern in meta['related_files'])] for path in paths}


def main(argv=None, root=ROOT):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    sub.add_parser('build', help='regenerate docs/README.md and .claude/skills copies')
    sub.add_parser('check', help='validate metadata and detect a stale index or skill copy')
    query = sub.add_parser('for', help='find guides for relative source paths, including deleted files')
    query.add_argument('paths', nargs='+')
    query.add_argument('--json', action='store_true')
    args = parser.parse_args(argv)
    try:
        # Mirrors come first so guide metadata may reference the generated copies.
        if args.command == 'build':
            sync_mirrors(root)
        elif args.command == 'check' and stale_mirrors(root):
            raise ValueError('Claude Code skill copies are stale: ' + ', '.join(stale_mirrors(root))
                             + '; edit .agents/skills, then run python scripts/docs.py build')
        records = load(root)
        index = root / 'docs' / 'README.md'
        readme = readme_with_results(root) if args.command != 'for' else None
        if args.command == 'build':
            index.write_text(render(records), encoding='utf-8', newline='\n')
            if readme is not None:
                (root / 'README.md').write_text(readme[1], encoding='utf-8', newline='\n')
            print('Updated docs/README.md' + (' and .claude/skills' if skill_mirrors(root) else '')
                  + (' and README results' if readme is not None else ''))
        elif args.command == 'check':
            if not index.exists() or index.read_text(encoding='utf-8') != render(records):
                raise ValueError('Documentation index is stale; run python scripts/docs.py build')
            if readme is not None and readme[0] != readme[1]:
                raise ValueError('README results table differs from the recorded summary; '
                                 'run python scripts/docs.py build')
            diagram = stale_diagram(root)
            if diagram:
                raise ValueError(diagram)
            broken = broken_links(root, records)
            if broken:
                raise ValueError('Broken relative links: ' + '; '.join(broken))
            print(f'Documentation OK: {len(records)} current guides/templates')
        else:
            matches = lookup(records, args.paths)
            if args.json:
                print(json.dumps(matches, ensure_ascii=False, indent=2))
            else:
                for path, names in matches.items():
                    print(f'{path}: ' + (', '.join(names) or 'UNMAPPED: inspect and add a related_files entry if needed'))
            return 0 if all(matches.values()) else 1
        return 0
    except (ValueError, OSError) as error:
        print(str(error), file=sys.stderr)
        return 2


if __name__ == '__main__':
    raise SystemExit(main())
