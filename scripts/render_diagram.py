"""Render docs/architecture.mmd to docs/architecture.svg with Mermaid in a browser.

Usage: python scripts/render_diagram.py [--port 48214]
Open the printed http://127.0.0.1 address in any browser. The page renders the
diagram with a pinned Mermaid version and sends the SVG back; this script stamps
it with the source hash, writes docs/architecture.svg and exits.
`python scripts/docs.py check` fails when the stamp no longer matches the source.
Standard library only; the browser loads Mermaid from cdn.jsdelivr.net.
"""
import argparse
import hashlib
import html
from http.server import BaseHTTPRequestHandler, HTTPServer
from pathlib import Path
import threading

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'docs' / 'architecture.mmd'
TARGET = ROOT / 'docs' / 'architecture.svg'
MERMAID = 'https://cdn.jsdelivr.net/npm/mermaid@10.9.1/dist/mermaid.min.js'


def source_hash(text):
    return hashlib.sha256(text.replace('\r\n', '\n').encode('utf-8')).hexdigest()


def stamp(text):
    return (f'<!-- Generated by scripts/render_diagram.py from docs/architecture.mmd; '
            f'source-sha256: {source_hash(text)} -->\n')


PAGE = '''<!doctype html><html><head><meta charset="utf-8"><title>Render diagram</title></head>
<body style="background:#fff"><pre id="src" hidden>{source}</pre><div id="out"></div><p id="status">rendering</p>
<script src="{mermaid}"></script>
<script>
mermaid.initialize({{startOnLoad: false, theme: 'default', securityLevel: 'strict',
  flowchart: {{htmlLabels: false, curve: 'basis'}}, themeVariables: {{fontSize: '16px'}}}});
mermaid.render('architecture', document.getElementById('src').textContent).then(({{svg}}) => {{
  document.getElementById('out').innerHTML = svg;
  return fetch('/save', {{method: 'POST', body: svg}});
}}).then(r => r.text()).then(t => document.getElementById('status').textContent = t)
  .catch(e => document.getElementById('status').textContent = 'ERROR ' + e.message);
</script></body></html>'''


def with_background(svg):
    """Opaque white card so the diagram reads the same on light and dark pages."""
    head, rest = svg.split('>', 1)
    return f'{head}><rect x="-50%" y="-50%" width="200%" height="200%" fill="#ffffff"/>{rest}'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--port', type=int, default=48214)
    args = parser.parse_args()
    text = SOURCE.read_text(encoding='utf-8')
    page = PAGE.format(source=html.escape(text), mermaid=MERMAID).encode('utf-8')
    done = threading.Event()

    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *_):
            pass

        def do_GET(self):
            self.send_response(200)
            self.send_header('Content-Type', 'text/html; charset=utf-8')
            self.end_headers()
            self.wfile.write(page)

        def do_POST(self):
            body = self.rfile.read(int(self.headers['Content-Length'])).decode('utf-8')
            if self.path != '/save' or not body.startswith('<svg'):
                self.send_response(400)
                self.end_headers()
                return
            TARGET.write_text(stamp(text) + with_background(body) + '\n', encoding='utf-8', newline='\n')
            self.send_response(200)
            self.end_headers()
            self.wfile.write(f'saved {TARGET.relative_to(ROOT).as_posix()}'.encode())
            done.set()

    server = HTTPServer(('127.0.0.1', args.port), Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    print(f'Open http://127.0.0.1:{args.port}/ in a browser to render {SOURCE.relative_to(ROOT)}', flush=True)
    done.wait()
    server.shutdown()
    print(f'Wrote {TARGET.relative_to(ROOT).as_posix()}')


if __name__ == '__main__':
    main()
